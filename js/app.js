      async function handleThreatFormSubmit(event) {
        event.preventDefault();
        const user = getCurrentUser();
        if (!user || !user.isAdmin) {
          showToast('Управлять реестром может только администратор.', 'error');
          return;
        }

        const title = dom.threatTitleInput.value.trim();
        const desc = dom.threatDescInput.value.trim();
        const type = dom.threatTypeInput.value;
        const severity = dom.threatSeverityInput.value;
        const example = dom.threatExampleInput.value.trim();

        if (title.length < 3) {
          showThreatFormError('Название должно содержать минимум 3 символа.', dom.threatTitleInput);
          return;
        }
        if (!THREAT_TYPES[type]) {
          showThreatFormError('Выберите тип записи.', dom.threatTypeInput);
          return;
        }
        if (desc.length < 10) {
          showThreatFormError('Добавьте описание — минимум 10 символов.', dom.threatDescInput);
          return;
        }
        if (!SEVERITIES[severity]) {
          showThreatFormError('Выберите уровень риска.', dom.threatSeverityInput);
          return;
        }

        // Серверный режим: запись сохраняется в общей базе.
        if (isServerMode()) {
          try {
            await api().threats.create({ title, description: desc, severity, type, example });
            try {
              const list = await api().threats.list();
              state.threats = list.map(normalizeStoredThreat).filter(Boolean);
            } catch (reloadError) {
              console.warn('CyberShield: реестр не перечитан.', reloadError);
            }
            state.registryFilter = 'all';
            state.registryTypeFilter = 'all';
            state.registrySearch = '';
            if (dom.registrySearch) dom.registrySearch.value = '';
            dom.threatForm.reset();
            dom.threatTypeInput.value = 'site';
            dom.threatSeverityInput.value = 'medium';
            clearThreatFormFeedback();
            renderRegistry();
            showToast('Запись добавлена в реестр опасностей.', 'success');
          } catch (error) {
            showThreatFormError(error.message || 'Не удалось сохранить запись. Попробуйте ещё раз.', null);
          }
          return;
        }

        const newThreat = {
          id: createId('threat'),
          title,
          desc,
          severity,
          type,
          example
        };
        const nextThreats = [newThreat, ...state.threats];
        const write = persistJSON(STORAGE_KEYS.threats, nextThreats);
        if (!write.ok) {
          showThreatFormError('Не удалось сохранить запись. Попробуйте ещё раз.', null);
          showToast('Не удалось сохранить запись в реестре.', 'error');
          return;
        }

        state.threats = nextThreats;
        state.registryFilter = 'all';
        state.registryTypeFilter = 'all';
        state.registrySearch = '';
        if (dom.registrySearch) dom.registrySearch.value = '';
        dom.threatForm.reset();
        dom.threatTypeInput.value = 'site';
        dom.threatSeverityInput.value = 'medium';
        clearThreatFormFeedback();
        renderRegistry();
        showToast('Запись добавлена в реестр опасностей.', 'success');
      }

      async function deleteThreat(threatId) {
        const user = getCurrentUser();
        if (!user || !user.isAdmin) {
          showToast('Удалять записи может только администратор.', 'error');
          return;
        }

        const threat = state.threats.find((entry) => entry.id === threatId);
        if (!threat) return;

        const confirmed = window.confirm(`Удалить запись «${threat.title}» из реестра?`);
        if (!confirmed) return;

        if (isServerMode()) {
          try {
            await api().threats.remove(threatId);
            const list = await api().threats.list();
            state.threats = list.map(normalizeStoredThreat).filter(Boolean);
            renderRegistry();
            showToast('Запись удалена из реестра.', 'success');
          } catch (error) {
            showToast(error.message || 'Не удалось удалить запись.', 'error');
          }
          return;
        }

        const nextThreats = state.threats.filter((entry) => entry.id !== threatId);
        const write = persistJSON(STORAGE_KEYS.threats, nextThreats);
        if (!write.ok) {
          showToast('Не удалось удалить запись. Попробуйте ещё раз.', 'error');
          return;
        }

        state.threats = nextThreats;
        renderRegistry();
        showToast('Запись удалена из реестра.', 'success');
      }

