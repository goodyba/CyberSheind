      function describeDevice() {
        const ua = String(navigator.userAgent || '');
        let browser = 'Браузер';
        if (/YaBrowser\//.test(ua)) browser = 'Yandex Browser';
        else if (/Edg\//.test(ua)) browser = 'Edge';
        else if (/OPR\/|Opera/.test(ua)) browser = 'Opera';
        else if (/Firefox\//.test(ua)) browser = 'Firefox';
        else if (/Chrome\//.test(ua)) browser = 'Chrome';
        else if (/Safari\//.test(ua)) browser = 'Safari';

        let os = 'неизвестная ОС';
        if (/Windows/.test(ua)) os = 'Windows';
        else if (/Android/.test(ua)) os = 'Android';
        else if (/iPhone|iPad|iPod/.test(ua)) os = 'iOS';
        else if (/Mac OS X/.test(ua)) os = 'macOS';
        else if (/Linux/.test(ua)) os = 'Linux';

        return `${browser} · ${os}`;
      }

      function computeDeviceId() {
        const parts = [
          navigator.userAgent || '',
          navigator.language || '',
          Array.isArray(navigator.languages) ? navigator.languages.join(',') : '',
          navigator.platform || '',
          String(navigator.hardwareConcurrency || 0),
          String(navigator.maxTouchPoints || 0),
          `${window.screen ? window.screen.width : 0}x${window.screen ? window.screen.height : 0}x${window.screen ? window.screen.colorDepth : 0}`,
          String(window.devicePixelRatio || 1),
          Intl.DateTimeFormat().resolvedOptions().timeZone || '',
          String(new Date().getTimezoneOffset())
        ].join('|');

        let hash = '';
        try {
          hash = bytesToHex(sha256Bytes(parts)).slice(0, 24);
        } catch (error) {
          hash = String(parts.length);
        }
        return `dev_${hash}`;
      }

      /* IP определяется по открытому сервису. Если сети нет (file://, офлайн,
         запрет CORS) — возвращаем null, и тогда сверяется только устройство. */
      async function detectPublicIp(force = false) {
        const now = Date.now();
        // Короткий кеш: за один вход запрос может понадобиться дважды,
        // но перед каждым новым входом адрес перепроверяется.
        if (!force && state.accessIp && now - state.accessIpAt < 20000) return state.accessIp;

        const attempt = async (endpoint, signal) => {
          const response = await fetch(endpoint, { signal, cache: 'no-store', mode: 'cors' });
          if (!response.ok) throw new Error('ip lookup failed');
          const data = await response.json();
          const ip = typeof data === 'string' ? data : data && (data.ip || data.query);
          if (typeof ip !== 'string' || !/^[0-9a-fA-F:.]{3,45}$/.test(ip.trim())) {
            throw new Error('ip lookup returned no address');
          }
          return ip.trim();
        };

        const controller = typeof AbortController === 'function' ? new AbortController() : null;
        const timer = controller ? window.setTimeout(() => controller.abort(), 2200) : null;
        try {
          // Оба адреса спрашиваются параллельно: первый ответ и побеждает.
          const ip = await Promise.any(IP_ENDPOINTS.map((endpoint) => attempt(endpoint, controller ? controller.signal : undefined)));
          state.accessIp = ip;
          state.accessIpAt = Date.now();
          return ip;
        } catch (error) {
          // Офлайн-режим, file:// или CORS — запоминаем, что адрес недоступен.
          state.accessIpAt = Date.now();
          return state.accessIp || null;
        } finally {
          if (timer) window.clearTimeout(timer);
        }
      }

