      async function registerAccount() {
        if (isServerMode()) {
          await registerOnServer();
          return;
        }

        const name = dom.regName.value.trim();
        const email = normalizeEmail(dom.authEmail.value);
        const password = dom.authPassword.value;
        const confirmation = dom.regPasswordConfirm.value;

        if (name.length < 2) {
          authValidationError('Введите имя — минимум 2 символа.', dom.regName);
          return;
        }
        if (!isValidEmail(email)) {
          authValidationError('Введите корректный email, например name@example.com.', dom.authEmail);
          return;
        }
        if (password.length < 6) {
          authValidationError('Пароль должен содержать минимум 6 символов.', dom.authPassword);
          return;
        }
        if (password !== confirmation) {
          authValidationError('Пароли не совпадают.', dom.regPasswordConfirm);
          return;
        }
        if (email === ADMIN_EMAIL) {
          authValidationError('Этот email зарезервирован для администратора.', dom.authEmail);
          return;
        }
        if (state.users.some((user) => user.email === email)) {
          authValidationError('Аккаунт с таким email уже существует. Войдите или укажите другой.', dom.authEmail);
          return;
        }

        setAuthBusy(true);

        try {
          // Даём браузеру отрисовать состояние загрузки до синхронного хеширования.
          await waitForPaint();

          const salt = makeSalt();
          const passwordHash = hashPassword(password, salt, PASSWORD_HASH_ITERATIONS);
          const newUser = {
            id: createId('user'),
            name,
            email,
            passwordHash,
            salt,
            hashIterations: PASSWORD_HASH_ITERATIONS,
            createdAt: new Date().toISOString(),
            results: []
          };
          const nextUsers = [...state.users, newUser];
          const usersSaved = persistJSON(STORAGE_KEYS.users, nextUsers);
          if (!usersSaved.ok) {
            setAuthFeedback('Не удалось сохранить аккаунт. Попробуйте ещё раз.', 'error');
            return;
          }

          state.users = nextUsers;

          // Регистрация — это первый вход: запоминаем устройство и IP-адрес,
          // чтобы при следующем входе заметить смену устройства или сети.
          const context = await collectAccessContext();
          const record = getDeviceRecord(newUser.email, newUser.name);
          rememberDevice(record, context);
          pushSecurityLog(record, 'register', 'Регистрация: устройство и IP запомнены');
          persistDevices();
          state.lastAccess = context;

          dom.authForm.reset();
          clearAuthFeedback();
          completeLogin(newUser.email, false, 'Аккаунт создан. Устройство запомнено для следующих входов.');
        } catch (error) {
          console.error('CyberShield: ошибка регистрации.', error);
          setAuthFeedback('Не удалось завершить регистрацию. Попробуйте ещё раз.', 'error');
        } finally {
          setAuthBusy(false);
        }
      }

      async function loginAccount() {
        if (isServerMode()) {
          await loginOnServer();
          return;
        }

        const email = normalizeEmail(dom.authEmail.value);
        const password = dom.authPassword.value;

        if (!isValidEmail(email)) {
          authValidationError('Введите корректный email.', dom.authEmail);
          return;
        }
        if (!password) {
          authValidationError('Введите пароль.', dom.authPassword);
          return;
        }

        setAuthBusy(true);

        try {
          await waitForPaint();
          let isAdmin = false;

          if (email === ADMIN_EMAIL) {
            if (password !== ADMIN.password) {
              authValidationError('Неверный email или пароль.', dom.authPassword);
              return;
            }
            isAdmin = true;
          } else {
            const user = state.users.find((entry) => entry.email === email);
            if (!user) {
              authValidationError('Неверный email или пароль.', dom.authPassword);
              return;
            }

            const candidateHash = hashPassword(password, user.salt, user.hashIterations);
            if (candidateHash !== user.passwordHash) {
              authValidationError('Неверный email или пароль.', dom.authPassword);
              return;
            }
          }

          // Контроль доступа: если устройство или IP отличаются от первого входа,
          // вход не завершается — сначала код подтверждения «из письма».
          const context = await collectAccessContext();
          const record = getDeviceRecord(email, isAdmin ? ADMIN.name : '');
          const verdict = evaluateAccess(record, context);
          if (record.forceCheck) {
            verdict.needsCode = true;
            verdict.deviceChanged = true;
          }

          if (verdict.needsCode) {
            startDeviceChallenge({ email, isAdmin, context, verdict });
            return;
          }

          rememberDevice(record, context);
          pushSecurityLog(
            record,
            'login',
            verdict.isFirst ? 'Первый вход: устройство и IP запомнены' : 'Вход с доверенного устройства'
          );
          persistDevices();
          state.lastAccess = context;

          completeLogin(email, isAdmin, isAdmin ? 'Служебный доступ открыт.' : 'Вход выполнен.');
        } catch (error) {
          console.error('CyberShield: ошибка входа.', error);
          setAuthFeedback('Не удалось выполнить вход. Попробуйте ещё раз.', 'error');
        } finally {
          setAuthBusy(false);
        }
      }

      /* Общий финал входа: создаёт сессию, обновляет экраны и показывает кабинет.
         Вызывается и после обычного входа, и после подтверждения кодом. */
      function completeLogin(email, isAdmin, message) {
        const session = { email: normalizeEmail(email), isAdmin: Boolean(isAdmin) };
        const sessionSaved = persistJSON(STORAGE_KEYS.session, session);
        if (!sessionSaved.ok) {
          setAuthFeedback('Не удалось сохранить сессию. Попробуйте ещё раз.', 'error');
          return;
        }

        state.session = session;
        if (dom.authForm) dom.authForm.reset();
        clearAuthFeedback();
        updateNavigation();
        renderDashboard();
        showScreen('dashboard');
        showToast(message || (session.isAdmin ? 'Служебный доступ открыт.' : 'Вход выполнен.'), 'success');
      }

