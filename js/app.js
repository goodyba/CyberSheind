      function animateResultProgress(targetPercent) {
        const token = state.resultAnimationToken + 1;
        state.resultAnimationToken = token;
        const finalOffset = RING_CIRCUMFERENCE * (1 - targetPercent / 100);

        dom.resultPercent.textContent = '0';
        dom.ringProgress.style.transition = 'none';
        dom.ringProgress.style.strokeDashoffset = String(RING_CIRCUMFERENCE);
        void dom.ringProgress.getBoundingClientRect();

        if (REDUCED_MOTION) {
          dom.ringProgress.style.transition = '';
          dom.ringProgress.style.strokeDashoffset = String(finalOffset);
          dom.resultPercent.textContent = String(targetPercent);
          return;
        }

        dom.ringProgress.style.transition = '';
        window.requestAnimationFrame(() => {
          if (token !== state.resultAnimationToken) return;
          dom.ringProgress.style.strokeDashoffset = String(finalOffset);

          const duration = 1150;
          const startedAt = performance.now();

          function updateCounter(now) {
            if (token !== state.resultAnimationToken) return;
            const progress = Math.min(1, (now - startedAt) / duration);
            const eased = 1 - Math.pow(1 - progress, 3);
            dom.resultPercent.textContent = String(Math.round(targetPercent * eased));
            if (progress < 1) {
              window.requestAnimationFrame(updateCounter);
            } else {
              dom.resultPercent.textContent = String(targetPercent);
            }
          }

          window.requestAnimationFrame(updateCounter);
        });
      }

