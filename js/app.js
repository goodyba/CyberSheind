      function sortedForumTopics() {
        const topics = [...state.forumTopics];
        const byPinned = (first, second) => Number(second.pinned) - Number(first.pinned);
        const byUpdated = (first, second) => (new Date(second.updatedAt).getTime() || 0) - (new Date(first.updatedAt).getTime() || 0);
        const byCreated = (first, second) => (new Date(second.createdAt).getTime() || 0) - (new Date(first.createdAt).getTime() || 0);

        if (state.forumSort === 'fresh') return topics.sort((first, second) => byPinned(first, second) || byCreated(first, second));
        if (state.forumSort === 'unanswered') {
          return topics
            .filter((topic) => topic.posts.length === 0)
            .sort((first, second) => byPinned(first, second) || byUpdated(first, second));
        }
        return topics.sort((first, second) => byPinned(first, second) || byUpdated(first, second));
      }

