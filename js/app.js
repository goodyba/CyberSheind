      function normalizeStoredThreat(raw) {
        if (!raw || typeof raw !== 'object') return null;
        const title = String(raw.title || '').trim().slice(0, 90);
        const desc = String(raw.desc || '').trim().slice(0, 350);
        if (!title || !desc) return null;
        let id = String(raw.id || '');
        if (!/^[a-zA-Z0-9_-]{1,100}$/.test(id)) id = createId('threat');
        const severity = ['high', 'medium', 'low'].includes(raw.severity) ? raw.severity : 'medium';
        const type = Object.prototype.hasOwnProperty.call(THREAT_TYPES, raw.type) ? raw.type : 'practice';
        const example = String(raw.example || '').trim().slice(0, 160);
        return { id, title, desc, severity, type, example };
      }

      function getStarterThreats() {
        return STARTER_THREATS.map((threat) => ({ ...threat }));
      }

      function normalizeThreatList(list) {
        const seen = new Set();
        return list
          .map(normalizeStoredThreat)
          .filter((threat) => {
            if (!threat) return false;
            if (seen.has(threat.id)) threat.id = createId('threat');
            seen.add(threat.id);
            return true;
          });
      }

      // Переносит старые записи реестра в новую схему и добавляет новые
      // стартовые карточки, не воскрешая удалённые старые записи.
      function migrateLegacyThreats(legacyRaw) {
        const parsed = JSON.parse(legacyRaw);
        if (!Array.isArray(parsed)) throw new Error('Некорректный формат старого реестра');
        const seedsById = new Map(STARTER_THREATS.map((threat) => [threat.id, threat]));
        const migrated = normalizeThreatList(parsed).map((threat) => {
          const seed = seedsById.get(threat.id);
          if (!seed) return threat;
          return {
            ...threat,
            type: seed.type || threat.type,
            example: threat.example || seed.example || ''
          };
        });
        const existingIds = new Set(migrated.map((threat) => threat.id));
        STARTER_THREATS.slice(10).forEach((seed) => {
          if (!existingIds.has(seed.id)) migrated.push({ ...seed });
        });
        return migrated;
      }

      function loadThreats() {
        try {
          let raw = SafeStorage.getItem(STORAGE_KEYS.threats);
          let needsMigrationSave = false;

          if (raw === null) {
            const legacyRaw = SafeStorage.getItem(STORAGE_KEYS.threatsLegacy);
            if (legacyRaw !== null) {
              try {
                raw = JSON.stringify(migrateLegacyThreats(legacyRaw));
                needsMigrationSave = true;
              } catch (migrationError) {
                console.warn('CyberShield: старый реестр не удалось перенести, будет создан новый.', migrationError);
                raw = null;
              }
            }
          }

          if (raw === null) {
            const seeded = getStarterThreats();
            raw = JSON.stringify(seeded);
            needsMigrationSave = true;
          }

          const parsed = JSON.parse(raw);
          if (!Array.isArray(parsed)) throw new Error('Некорректный формат реестра');
          const threats = normalizeThreatList(parsed);

          if (needsMigrationSave) {
            try {
              SafeStorage.setItem(STORAGE_KEYS.threats, JSON.stringify(threats));
            } catch (error) {
              console.warn('CyberShield: реестр сохранён только в памяти.', error);
            }
          }

          return threats;
        } catch (error) {
          console.error('CyberShield: не удалось прочитать реестр, восстанавливаем стартовый список.', error);
          const seeded = getStarterThreats();
          try {
            SafeStorage.setItem(STORAGE_KEYS.threats, JSON.stringify(seeded));
          } catch (saveError) {
            console.warn('CyberShield: не удалось перезаписать повреждённый реестр.', saveError);
          }
          return seeded;
        }
      }

