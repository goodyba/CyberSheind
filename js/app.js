      function normalizeForumPost(raw) {
        if (!raw || typeof raw !== 'object') return null;
        const body = String(raw.body || '').trim().slice(0, 4000);
        if (!body) return null;
        return {
          id: typeof raw.id === 'string' && raw.id ? raw.id.slice(0, 90) : createId('post'),
          authorEmail: normalizeEmail(raw.authorEmail),
          authorName: String(raw.authorName || 'Участник').trim().slice(0, 60) || 'Участник',
          isAdmin: raw.isAdmin === true,
          body,
          createdAt: raw.createdAt || new Date().toISOString()
        };
      }

      function normalizeForumTopic(raw) {
        if (!raw || typeof raw !== 'object') return null;
        const title = String(raw.title || '').trim().slice(0, 120);
        const body = String(raw.body || '').trim().slice(0, 4000);
        if (!title || !body) return null;
        const category = Object.prototype.hasOwnProperty.call(FORUM_CATEGORIES, raw.category) ? raw.category : 'help';
        const createdAt = raw.createdAt || new Date().toISOString();
        return {
          id: typeof raw.id === 'string' && raw.id ? raw.id.slice(0, 90) : createId('topic'),
          title,
          body,
          category,
          authorEmail: normalizeEmail(raw.authorEmail),
          authorName: String(raw.authorName || 'Участник').trim().slice(0, 60) || 'Участник',
          isAdmin: raw.isAdmin === true,
          createdAt,
          updatedAt: raw.updatedAt || createdAt,
          pinned: raw.pinned === true,
          locked: raw.locked === true,
          views: Number.isFinite(Number(raw.views)) ? Math.max(0, Math.round(Number(raw.views))) : 0,
          posts: Array.isArray(raw.posts) ? raw.posts.map(normalizeForumPost).filter(Boolean).slice(0, 300) : []
        };
      }

      function loadForum() {
        try {
          const raw = SafeStorage.getItem(STORAGE_KEYS.forum);
          if (!raw) {
            const seeded = forumStarterTopics();
            persistJSON(STORAGE_KEYS.forum, { topics: seeded });
            return seeded;
          }
          const parsed = JSON.parse(raw);
          const list = Array.isArray(parsed) ? parsed : parsed && Array.isArray(parsed.topics) ? parsed.topics : null;
          if (!list) return forumStarterTopics();

          const seen = new Set();
          return list.map(normalizeForumTopic).filter((topic) => {
            if (!topic) return false;
            if (seen.has(topic.id)) topic.id = createId('topic');
            seen.add(topic.id);
            return true;
          });
        } catch (error) {
          console.error('CyberShield: не удалось прочитать форум.', error);
          return forumStarterTopics();
        }
      }

