      /* =====================================================================
         TOAST-УВЕДОМЛЕНИЯ
         ===================================================================== */
      function removeToast(toast) {
        if (!toast || !toast.isConnected || toast.classList.contains('is-leaving')) return;
        window.clearTimeout(toast._hideTimer);
        toast.classList.add('is-leaving');
        window.setTimeout(() => toast.remove(), 240);
      }

      function showToast(message, type = 'success', duration = 4300) {
        if (!dom.toastRegion) return;
        const safeType = ['success', 'error', 'warning', 'info'].includes(type) ? type : 'success';
        while (dom.toastRegion.children.length >= 4) {
          const oldest = dom.toastRegion.firstElementChild;
          if (!oldest) break;
          window.clearTimeout(oldest._hideTimer);
          oldest.remove();
        }

        const toast = document.createElement('div');
        toast.className = `toast toast--${safeType}`;

        const icon = document.createElement('span');
        icon.className = 'toast-icon';
        icon.setAttribute('aria-hidden', 'true');
        icon.textContent = safeType === 'success' ? '✓' : safeType === 'info' ? 'i' : '!';

        const text = document.createElement('p');
        text.className = 'toast-message';
        text.textContent = message;

        const close = document.createElement('button');
        close.className = 'toast-close';
        close.type = 'button';
        close.setAttribute('aria-label', 'Закрыть уведомление');
        close.textContent = '×';
        close.addEventListener('click', () => removeToast(toast));

        toast.append(icon, text, close);
        dom.toastRegion.append(toast);
        toast._hideTimer = window.setTimeout(() => removeToast(toast), duration);
      }

