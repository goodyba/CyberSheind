      function launchConfetti() {
        if (REDUCED_MOTION) return;
        const canvas = document.getElementById('confettiCanvas');
        if (!canvas) return;
        const context = canvas.getContext('2d');
        if (!context) return;

        if (confettiFrame) {
          window.cancelAnimationFrame(confettiFrame);
          confettiFrame = null;
        }

        const dpr = Math.min(window.devicePixelRatio || 1, 2);
        const width = window.innerWidth;
        const height = window.innerHeight;
        canvas.width = Math.floor(width * dpr);
        canvas.height = Math.floor(height * dpr);
        context.setTransform(dpr, 0, 0, dpr, 0, 0);

        const colors = ['#6c5ce7', '#22d3ee', '#a78bfa', '#f472b6', '#facc15', '#34d399', '#ffffff'];
        const pieceCount = clamp(Math.round(width / 8), 100, 180);
        const pieces = Array.from({ length: pieceCount }, () => ({
          x: Math.random() * width,
          y: -20 - Math.random() * height * 0.45,
          vx: (Math.random() - 0.5) * 1.8,
          vy: 1.7 + Math.random() * 3.2,
          width: 4 + Math.random() * 7,
          height: 7 + Math.random() * 8,
          rotation: Math.random() * Math.PI * 2,
          spin: (Math.random() - 0.5) * 0.22,
          color: colors[Math.floor(Math.random() * colors.length)],
          shape: Math.random() > 0.76 ? 'circle' : 'rect',
          sway: Math.random() * Math.PI * 2,
          swaySpeed: 0.004 + Math.random() * 0.008
        }));

        const startedAt = performance.now();
        const duration = 4300;

        function drawFrame(now) {
          const elapsed = now - startedAt;
          const fadeOut = elapsed > 3200 ? Math.max(0, 1 - (elapsed - 3200) / 1200) : 1;
          context.clearRect(0, 0, width, height);

          pieces.forEach((piece) => {
            piece.vy += 0.045;
            piece.x += piece.vx + Math.sin(elapsed * piece.swaySpeed + piece.sway) * 0.4;
            piece.y += piece.vy;
            piece.rotation += piece.spin;

            if (piece.y > height + 30) return;

            context.save();
            context.globalAlpha = fadeOut;
            context.fillStyle = piece.color;
            context.translate(piece.x, piece.y);
            context.rotate(piece.rotation);
            if (piece.shape === 'circle') {
              context.beginPath();
              context.arc(0, 0, piece.width / 2, 0, Math.PI * 2);
              context.fill();
            } else {
              context.fillRect(-piece.width / 2, -piece.height / 2, piece.width, piece.height);
            }
            context.restore();
          });

          if (elapsed < duration && state.currentScreen === 'result') {
            confettiFrame = window.requestAnimationFrame(drawFrame);
          } else {
            context.clearRect(0, 0, width, height);
            confettiFrame = null;
          }
        }

        confettiFrame = window.requestAnimationFrame(drawFrame);
      }

      let particleFrame = null;

      function initParticleNetwork() {
        const canvas = document.getElementById('particleCanvas');
        if (!canvas) return;
        const context = canvas.getContext('2d');
        if (!context) return;

        let width = window.innerWidth;
        let height = window.innerHeight;
        let dpr = 1;
        let particles = [];
        const pointer = { x: null, y: null };

        function createParticle() {
          const palette = ['rgba(150, 163, 255, ALPHA)', 'rgba(92, 132, 255, ALPHA)', 'rgba(47, 211, 238, ALPHA)'];
          return {
            x: Math.random() * width,
            y: Math.random() * height,
            vx: (Math.random() - 0.5) * 0.26,
            vy: (Math.random() - 0.5) * 0.26,
            radius: 0.8 + Math.random() * 1.7,
            alpha: 0.2 + Math.random() * 0.46,
            color: palette[Math.floor(Math.random() * palette.length)]
          };
        }

        function resize() {
          width = window.innerWidth;
          height = window.innerHeight;
          dpr = Math.min(window.devicePixelRatio || 1, 2);
          canvas.width = Math.floor(width * dpr);
          canvas.height = Math.floor(height * dpr);
          context.setTransform(dpr, 0, 0, dpr, 0, 0);

          const desiredCount = clamp(Math.round((width * height) / 25000), 30, 82);
          particles = Array.from({ length: desiredCount }, createParticle);

          if (REDUCED_MOTION) drawStaticParticles();
        }

        function drawDots() {
          particles.forEach((particle) => {
            context.beginPath();
            context.fillStyle = particle.color.replace('ALPHA', String(particle.alpha));
            context.arc(particle.x, particle.y, particle.radius, 0, Math.PI * 2);
            context.fill();
          });
        }

        function drawConnections(animatePointer) {
          for (let first = 0; first < particles.length; first += 1) {
            const a = particles[first];
            for (let second = first + 1; second < particles.length; second += 1) {
              const b = particles[second];
              const distanceX = a.x - b.x;
              const distanceY = a.y - b.y;
              const distance = Math.hypot(distanceX, distanceY);
              if (distance < 128) {
                context.beginPath();
                context.strokeStyle = `rgba(119, 138, 255, ${(1 - distance / 128) * 0.15})`;
                context.lineWidth = 0.7;
                context.moveTo(a.x, a.y);
                context.lineTo(b.x, b.y);
                context.stroke();
              }
            }

            if (animatePointer && pointer.x !== null) {
              const distanceX = a.x - pointer.x;
              const distanceY = a.y - pointer.y;
              const distance = Math.hypot(distanceX, distanceY);
              if (distance < 180) {
                context.beginPath();
                context.strokeStyle = `rgba(34, 211, 238, ${(1 - distance / 180) * 0.25})`;
                context.lineWidth = 0.8;
                context.moveTo(a.x, a.y);
                context.lineTo(pointer.x, pointer.y);
                context.stroke();
              }
            }
          }
        }

        function drawStaticParticles() {
          context.clearRect(0, 0, width, height);
          drawConnections(false);
          drawDots();
        }

        function animate() {
          context.clearRect(0, 0, width, height);

          particles.forEach((particle) => {
            particle.x += particle.vx;
            particle.y += particle.vy;

            if (particle.x < -12) particle.x = width + 12;
            if (particle.x > width + 12) particle.x = -12;
            if (particle.y < -12) particle.y = height + 12;
            if (particle.y > height + 12) particle.y = -12;
          });

          drawConnections(true);
          drawDots();
          particleFrame = window.requestAnimationFrame(animate);
        }

        window.addEventListener('resize', resize, { passive: true });
        window.addEventListener('pointermove', (event) => {
          pointer.x = event.clientX;
          pointer.y = event.clientY;
        }, { passive: true });
        document.addEventListener('pointerleave', () => {
          pointer.x = null;
          pointer.y = null;
        });

        resize();
        if (!REDUCED_MOTION) {
          if (particleFrame) window.cancelAnimationFrame(particleFrame);
          particleFrame = window.requestAnimationFrame(animate);
        }
      }

