      function resendDeviceCode() {
        const challenge = state.deviceChallenge;
        if (!challenge) return;
        if (Date.now() < challenge.resendAvailableAt) return;

        if (challenge.remote) {
          challenge.resends += 1;
          challenge.resendAvailableAt = Date.now() + DEVICE_RESEND_COOLDOWN_MS;
          challenge.attempts = 0;
          updateResendButton();
          resendRemoteCode(challenge).then((ok) => {
            if (!ok) challenge.resendAvailableAt = Date.now();
            updateResendButton();
          });
          if (dom.deviceCodeInput) {
            dom.deviceCodeInput.value = '';
            dom.deviceCodeInput.focus({ preventScroll: true });
          }
          return;
        }

        challenge.code = generateEmailCode();
        challenge.expiresAt = Date.now() + DEVICE_CODE_TTL_MS;
        challenge.attempts = 0;
        challenge.resends += 1;
        challenge.resendAvailableAt = Date.now() + DEVICE_RESEND_COOLDOWN_MS;

        if (dom.deviceDemoCode) dom.deviceDemoCode.textContent = challenge.code;
        if (dom.deviceCodeInput) {
          dom.deviceCodeInput.value = '';
          dom.deviceCodeInput.focus({ preventScroll: true });
        }
        setDeviceFeedback('Новый код отправлен. Письмо обновлено ниже.', 'success');
        updateResendButton();
        showToast('Новый код отправлен на почту.', 'info');
      }

      function handleDeviceCodeSubmit(event) {
        event.preventDefault();
        const challenge = state.deviceChallenge;
        if (!challenge) return;

        const value = String(dom.deviceCodeInput.value || '').replace(/\D/g, '');
        if (value.length !== 6) {
          setDeviceFeedback('Введите 6 цифр из письма.');
          dom.deviceCodeInput.focus();
          return;
        }
        if (Date.now() > challenge.expiresAt) {
          setDeviceFeedback('Код истёк. Запросите новый — кнопка ниже.');
          return;
        }

        // Серверный режим: код проверяет backend, локально он не хранится.
        if (challenge.remote) {
          challenge.attempts += 1;
          if (dom.deviceVerifySubmit) dom.deviceVerifySubmit.disabled = true;
          setDeviceFeedback('Проверяем код…', 'success');
          submitRemoteCode(challenge, value).then((result) => {
            if (dom.deviceVerifySubmit) dom.deviceVerifySubmit.disabled = false;
            if (result.ok) return;
            if (result.expired) {
              setDeviceFeedback(result.message, 'warning');
              return;
            }
            setDeviceFeedback(result.message || 'Неверный код.');
            shakeDevicePanel();
            if (dom.deviceCodeInput) dom.deviceCodeInput.select();
          });
          return;
        }

        challenge.attempts += 1;

        if (value !== challenge.code) {
          if (challenge.attempts >= DEVICE_CODE_MAX_ATTEMPTS) {
            cancelDeviceChallenge('Слишком много неверных попыток. Вход отменён — попробуйте ещё раз.', 'error');
            showToast('Вход отменён: превышено число попыток.', 'error');
            return;
          }
          setDeviceFeedback(`Неверный код. Осталось попыток: ${DEVICE_CODE_MAX_ATTEMPTS - challenge.attempts}.`);
          shakeDevicePanel();
          dom.deviceCodeInput.select();
          return;
        }

        const record = getDeviceRecord(challenge.email, challenge.isAdmin ? ADMIN.name : '');
        rememberDevice(record, challenge.context);
        record.codeChecks = (Number(record.codeChecks) || 0) + 1;
        record.forceCheck = false;
        // Подтверждённый кодом адрес становится доверенным: иначе код
        // спрашивался бы при каждом входе из новой сети.
        if (challenge.context.ip) record.firstIp = challenge.context.ip;

        const reasonParts = [];
        if (challenge.verdict.deviceChanged) reasonParts.push('новое устройство');
        if (challenge.verdict.ipChanged) reasonParts.push('новый IP');
        pushSecurityLog(record, 'code', `Вход подтверждён кодом из письма${reasonParts.length ? ` · ${reasonParts.join(', ')}` : ''}`);
        persistDevices();

        state.lastAccess = challenge.context;

        const email = challenge.email;
        const isAdmin = challenge.isAdmin;
        finishDeviceChallenge();
        completeLogin(email, isAdmin, 'Вход подтверждён кодом из письма.');
      }

