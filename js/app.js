      function evaluateAccess(record, context) {
        const knownDevice = Boolean(
          record.firstDeviceId && (
            record.firstDeviceId === context.deviceId
            || record.devices.some((device) => device.deviceId === context.deviceId)
          )
        );
        const isFirst = !record.firstDeviceId;
        const deviceChanged = !isFirst && !knownDevice;
        const ipChanged = Boolean(context.ip && record.firstIp && context.ip !== record.firstIp);
        return { isFirst, deviceChanged, ipChanged, needsCode: deviceChanged || ipChanged };
      }

      function rememberDevice(record, context) {
        const now = new Date().toISOString();
        if (!record.firstDeviceId) {
          record.firstDeviceId = context.deviceId;
          record.firstSeen = now;
        }
        if (!record.firstIp && context.ip) record.firstIp = context.ip;

        const existing = record.devices.find((device) => device.deviceId === context.deviceId);
        if (existing) {
          existing.lastSeen = now;
          existing.label = context.deviceLabel;
          if (context.ip) existing.ip = context.ip;
        } else {
          record.devices = [
            {
              deviceId: context.deviceId,
              label: context.deviceLabel,
              ip: context.ip,
              firstSeen: now,
              lastSeen: now
            },
            ...record.devices
          ].slice(0, 8);
        }
        record.lastLoginAt = now;
      }

