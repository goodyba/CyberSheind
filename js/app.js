      function navigate(destination) {
        let target = destination;
        const user = getCurrentUser();

        if (target === 'home') target = user ? 'dashboard' : 'auth';

        if (target === 'auth' && user) target = 'dashboard';

        if (target === 'thread' && !state.forumTopicId) target = 'forum';

        if (['dashboard', 'quiz', 'result'].includes(target) && !user) {
          showToast('Сначала войдите в аккаунт.', 'warning');
          setAuthMode('login', { focus: false });
          showScreen('auth');
          return;
        }

        if (target === 'admin' && !(user && user.isAdmin)) {
          showToast('Панель администратора доступна только администратору.', 'error');
          if (user) {
            renderDashboard();
            showScreen('dashboard');
          } else {
            setAuthMode('login', { focus: false });
            showScreen('auth');
          }
          return;
        }

        switch (target) {
          case 'auth':
            setAuthMode('login', { focus: false });
            showScreen('auth');
            break;
          case 'dashboard':
            renderDashboard();
            showScreen('dashboard');
            break;
          case 'registry':
            renderRegistry();
            showScreen('registry');
            break;
          case 'forum':
            renderForum();
            showScreen('forum');
            break;
          case 'thread':
            if (!findForumTopic(state.forumTopicId)) {
              renderForum();
              showScreen('forum');
            } else {
              renderThread();
              showScreen('thread');
            }
            break;
          case 'admin':
            renderAdminPanel();
            showScreen('admin');
            break;
          case 'quiz':
            if (!state.quiz.active) startQuiz();
            else showScreen('quiz');
            break;
          case 'result':
            if (!state.currentResult) {
              renderDashboard();
              showScreen('dashboard');
            } else {
              showScreen('result');
            }
            break;
          default:
            break;
        }
      }

