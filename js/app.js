      /* Журнал входов → строки таблицы безопасности в админке. */
      function buildDeviceRecordsFromLog(log) {
        const byEmail = {};
        log.forEach((entry) => {
          const email = normalizeEmail(entry.email || '');
          if (!email) return;
          const at = entry.createdAt || new Date().toISOString();
          if (!byEmail[email]) {
            byEmail[email] = {
              email,
              name: entry.name || email,
              devices: [],
              firstDeviceId: '',
              firstIp: null,
              firstSeen: at,
              lastLoginAt: at,
              codeChecks: 0,
              forceCheck: false,
              log: []
            };
          }
          const record = byEmail[email];
          const label = entry.deviceLabel || 'неизвестное устройство';
          if (!record.devices.some((device) => device.label === label)) {
            record.devices.push({ deviceId: label, label, ip: entry.ip || null, firstSeen: at, lastSeen: at });
          }
          if (!record.firstIp && entry.ip) record.firstIp = entry.ip;
          if (new Date(at).getTime() > new Date(record.lastLoginAt).getTime()) record.lastLoginAt = at;
          if (entry.type === 'code') record.codeChecks += 1;
        });
        return byEmail;
      }

