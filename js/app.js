      function loadDevices() {
        try {
          const raw = SafeStorage.getItem(STORAGE_KEYS.devices);
          if (!raw) return {};
          const parsed = JSON.parse(raw);
          if (!parsed || typeof parsed !== 'object') return {};

          const result = {};
          Object.keys(parsed).forEach((key) => {
            const record = parsed[key];
            if (!record || typeof record !== 'object') return;
            const email = normalizeEmail(record.email || key);
            if (!email) return;
            result[email] = {
              email,
              name: typeof record.name === 'string' ? record.name.slice(0, 60) : '',
              devices: Array.isArray(record.devices)
                ? record.devices
                  .filter((device) => device && typeof device.deviceId === 'string' && device.deviceId)
                  .map((device) => ({
                    deviceId: device.deviceId.slice(0, 120),
                    label: String(device.label || 'Устройство').slice(0, 80),
                    ip: typeof device.ip === 'string' ? device.ip.slice(0, 45) : null,
                    firstSeen: device.firstSeen || '',
                    lastSeen: device.lastSeen || ''
                  }))
                  .slice(0, 8)
                : [],
              firstDeviceId: typeof record.firstDeviceId === 'string' ? record.firstDeviceId.slice(0, 120) : '',
              firstIp: typeof record.firstIp === 'string' ? record.firstIp.slice(0, 45) : null,
              firstSeen: record.firstSeen || '',
              lastLoginAt: record.lastLoginAt || '',
              codeChecks: Number.isFinite(Number(record.codeChecks)) ? Math.max(0, Math.round(Number(record.codeChecks))) : 0,
              forceCheck: record.forceCheck === true,
              log: Array.isArray(record.log)
                ? record.log
                  .filter((entry) => entry && typeof entry.type === 'string' && typeof entry.message === 'string')
                  .map((entry) => ({
                    id: typeof entry.id === 'string' ? entry.id : createId('log'),
                    type: entry.type.slice(0, 20),
                    message: entry.message.slice(0, 180),
                    at: entry.at || new Date().toISOString()
                  }))
                  .slice(0, 40)
                : []
            };
          });
          return result;
        } catch (error) {
          console.error('CyberShield: не удалось прочитать журнал устройств.', error);
          return {};
        }
      }

