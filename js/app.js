    function sha256Bytes(input) {
      const source = input instanceof Uint8Array ? input : new Uint8Array(input);
      const bitLength = source.length * 8;
      const paddedLength = (source.length + 9 + 63) & ~63;
      const buffer = new ArrayBuffer(paddedLength);
      const bytes = new Uint8Array(buffer);
      bytes.set(source);
      bytes[source.length] = 0x80;

      const dataView = new DataView(buffer);
      dataView.setUint32(paddedLength - 8, Math.floor(bitLength / 0x100000000));
      dataView.setUint32(paddedLength - 4, bitLength >>> 0);

      const state = new Uint32Array([
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
        0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19
      ]);
      const schedule = new Uint32Array(64);

      for (let offset = 0; offset < paddedLength; offset += 64) {
        for (let index = 0; index < 16; index += 1) {
          schedule[index] = dataView.getUint32(offset + index * 4);
        }

        for (let index = 16; index < 64; index += 1) {
          const previous15 = schedule[index - 15];
          const previous2 = schedule[index - 2];
          const sigma0 = rotateRight(previous15, 7) ^ rotateRight(previous15, 18) ^ (previous15 >>> 3);
          const sigma1 = rotateRight(previous2, 17) ^ rotateRight(previous2, 19) ^ (previous2 >>> 10);
          schedule[index] = (schedule[index - 16] + sigma0 + schedule[index - 7] + sigma1) >>> 0;
        }

        let a = state[0];
        let b = state[1];
        let c = state[2];
        let d = state[3];
        let e = state[4];
        let f = state[5];
        let g = state[6];
        let h = state[7];

        for (let index = 0; index < 64; index += 1) {
          const sum1 = rotateRight(e, 6) ^ rotateRight(e, 11) ^ rotateRight(e, 25);
          const choose = (e & f) ^ (~e & g);
          const temp1 = (h + sum1 + choose + SHA256_CONSTANTS[index] + schedule[index]) >>> 0;
          const sum0 = rotateRight(a, 2) ^ rotateRight(a, 13) ^ rotateRight(a, 22);
          const majority = (a & b) ^ (a & c) ^ (b & c);
          const temp2 = (sum0 + majority) >>> 0;

          h = g;
          g = f;
          f = e;
          e = (d + temp1) >>> 0;
          d = c;
          c = b;
          b = a;
          a = (temp1 + temp2) >>> 0;
        }

        state[0] = (state[0] + a) >>> 0;
        state[1] = (state[1] + b) >>> 0;
        state[2] = (state[2] + c) >>> 0;
        state[3] = (state[3] + d) >>> 0;
        state[4] = (state[4] + e) >>> 0;
        state[5] = (state[5] + f) >>> 0;
        state[6] = (state[6] + g) >>> 0;
        state[7] = (state[7] + h) >>> 0;
      }

      const result = new Uint8Array(32);
      const resultView = new DataView(result.buffer);
      for (let index = 0; index < 8; index += 1) {
        resultView.setUint32(index * 4, state[index]);
      }
      return result;
    }

