      function handleGlobalClick(event) {
        const navigationElement = event.target.closest('[data-nav]');
        if (navigationElement) {
          event.preventDefault();
          navigate(navigationElement.getAttribute('data-nav'));
          return;
        }

        const actionElement = event.target.closest('[data-action]');
        if (!actionElement) return;
        const action = actionElement.getAttribute('data-action');

        switch (action) {
          case 'start-test':
          case 'restart-test':
            event.preventDefault();
            startQuiz();
            break;
          case 'logout':
            event.preventDefault();
            logout();
            break;
          case 'filter-registry':
            event.preventDefault();
            filterRegistry(actionElement.getAttribute('data-severity'));
            break;
          case 'filter-registry-type':
            event.preventDefault();
            filterRegistryType(actionElement.getAttribute('data-type'));
            break;
          case 'open-topic':
            event.preventDefault();
            openForumTopic(actionElement.getAttribute('data-topic-id'));
            break;
          case 'forum-filter':
            event.preventDefault();
            state.forumCategory = actionElement.getAttribute('data-category') || 'all';
            renderForum();
            break;
          case 'forum-sort':
            event.preventDefault();
            state.forumSort = actionElement.getAttribute('data-sort') || 'active';
            renderForum();
            break;
          case 'toggle-forum-compose':
            event.preventDefault();
            toggleForumCompose();
            break;
          case 'delete-topic':
            event.preventDefault();
            deleteForumTopic(actionElement.getAttribute('data-topic-id'));
            break;
          case 'delete-post':
            event.preventDefault();
            deleteForumPost(actionElement.getAttribute('data-topic-id'), actionElement.getAttribute('data-post-id'));
            break;
          case 'toggle-pin-topic':
            event.preventDefault();
            toggleForumFlag(actionElement.getAttribute('data-topic-id'), 'pinned');
            break;
          case 'toggle-lock-topic':
            event.preventDefault();
            toggleForumFlag(actionElement.getAttribute('data-topic-id'), 'locked');
            break;
          case 'resend-device-code':
            event.preventDefault();
            resendDeviceCode();
            break;
          case 'cancel-device-verify':
            event.preventDefault();
            cancelDeviceChallenge('Подтверждение отменено. Войдите снова — или с уже доверенного устройства.', 'warning');
            break;
          case 'simulate-new-device':
            event.preventDefault();
            simulateNewDevice();
            break;
          case 'delete-threat':
            event.preventDefault();
            deleteThreat(actionElement.getAttribute('data-threat-id'));
            break;
          default:
            break;
        }
      }

      function bindEvents() {
        // Вкладки авторизации.
        dom.authTabs.forEach((tab) => {
          tab.addEventListener('click', () => {
            if (state.authBusy) return;
            const mode = tab.dataset.authMode;
            if (mode !== state.authMode) setAuthMode(mode, { reset: true, focus: true });
          });
        });

        dom.authForm.addEventListener('submit', handleAuthFormSubmit);

        dom.authForm.addEventListener('input', (event) => {
          if (!dom.authFeedback.hidden) {
            dom.authFeedback.hidden = true;
            dom.authFeedback.textContent = '';
            dom.authFeedback.className = 'form-feedback';
          }
          const field = event.target.closest('.field');
          if (field) {
            field.classList.remove('has-error');
            event.target.removeAttribute('aria-invalid');
          }
        });

        const threatInputs = [
          dom.threatTitleInput,
          dom.threatTypeInput,
          dom.threatSeverityInput,
          dom.threatExampleInput,
          dom.threatDescInput
        ];
        threatInputs.forEach((input) => {
          input.addEventListener('input', () => {
            if (!dom.threatFormFeedback.hidden) {
              dom.threatFormFeedback.hidden = true;
              dom.threatFormFeedback.textContent = '';
              dom.threatFormFeedback.className = 'form-feedback';
            }
            const field = input.closest('.field');
            if (field) field.classList.remove('has-error');
            input.removeAttribute('aria-invalid');
          });
        });

        dom.threatForm.addEventListener('submit', handleThreatFormSubmit);
        if (dom.registrySearch) {
          dom.registrySearch.addEventListener('input', () => {
            state.registrySearch = dom.registrySearch.value;
            renderRegistry();
          });
        }

        // Форум: поиск, новая тема и ответы.
        if (dom.forumSearch) {
          dom.forumSearch.addEventListener('input', () => {
            state.forumSearch = dom.forumSearch.value;
            renderForum();
          });
        }
        if (dom.forumTopicForm) dom.forumTopicForm.addEventListener('submit', handleForumTopicSubmit);
        if (dom.threadReplyForm) dom.threadReplyForm.addEventListener('submit', handleForumReplySubmit);
        [dom.forumTopicTitle, dom.forumTopicCategory, dom.forumTopicBody].forEach((input) => {
          if (!input) return;
          input.addEventListener('input', () => setForumFeedback(dom.forumTopicFeedback, ''));
        });
        if (dom.threadReplyBody) {
          dom.threadReplyBody.addEventListener('input', () => setForumFeedback(dom.threadReplyFeedback, ''));
        }

        // Подтверждение входа по коду.
        if (dom.deviceVerifyForm) dom.deviceVerifyForm.addEventListener('submit', handleDeviceCodeSubmit);
        if (dom.deviceCodeInput) {
          dom.deviceCodeInput.addEventListener('input', () => {
            const digits = String(dom.deviceCodeInput.value || '').replace(/\D/g, '').slice(0, 6);
            if (dom.deviceCodeInput.value !== digits) dom.deviceCodeInput.value = digits;
            if (dom.deviceVerifyFeedback && !dom.deviceVerifyFeedback.hidden) setDeviceFeedback('');
          });
        }
        dom.answersList.addEventListener('click', (event) => {
          const answer = event.target.closest('.answer');
          if (!answer || answer.disabled) return;
          selectAnswer(Number(answer.getAttribute('data-answer-index')));
        });

        document.addEventListener('click', handleGlobalClick);
        document.addEventListener('keydown', (event) => {
          if (state.currentScreen !== 'quiz' || state.quiz.answered) return;
          if (event.defaultPrevented || event.altKey || event.ctrlKey || event.metaKey || event.repeat) return;
          const answerIndex = Number(event.key) - 1;
          if (Number.isInteger(answerIndex) && answerIndex >= 0 && answerIndex < QUIZ_QUESTIONS[state.quiz.index].options.length) {
            event.preventDefault();
            selectAnswer(answerIndex);
          }
        });

        window.addEventListener('beforeunload', clearAnswerTimer);
      }

